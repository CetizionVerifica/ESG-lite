// DS-4 · writes the library seeds from src/studio/library/seeds/*.ts:
//   data/studio/templates/<kind>/<family>/{template.json, layouts/NN-<role>.json, thumbs/README.md}
//   data/studio/elements/<group>.json
//   src/reporting/studio/render/iconsLucide.ts   (the renderer's copy of the Lucide subset)
//
//   npm run seeds:ds-4            write the files (then `npm run sync:studio-render` for RENDER_HASH)
//   npm run seeds:ds-4 -- --check exit 1 when a committed file differs from the generator
//
// The Lucide paths come from lucide-static (a devDependency, ISC), pinned to the version the FE's
// lucide-react uses. data/studio/LICENSES.md is written by hand.
import fs from "fs";
import path from "path";
import { seedFiles } from "../studio/library/seeds";
import { LUCIDE_NAMES } from "../studio/library/seeds/lucide";

const ROOT = path.resolve(__dirname, "../..");
const DATA = path.join(ROOT, "data/studio");
const ICONS_TS = path.join(ROOT, "src/reporting/studio/render/iconsLucide.ts");

type IconNode = [string, Record<string, string | number>][];

export function lucideModule(): string {
  const nodes: Record<string, IconNode> = JSON.parse(fs.readFileSync(require.resolve("lucide-static/icon-nodes.json"), "utf8"));
  const version: string = JSON.parse(fs.readFileSync(require.resolve("lucide-static/package.json"), "utf8")).version;
  const esc = (v: string | number) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
  const lines = LUCIDE_NAMES().map((name) => {
    const node = nodes[name];
    if (!node) throw new Error(`lucide-static ${version} has no icon "${name}"`);
    const svg = node
      .map(([tag, attrs]) => `<${tag}${Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => ` ${k}="${esc(v)}"`)
        .join("")}/>`)
      .join("");
    return `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`;
  });
  return [
    "/**",
    ` * DS-4 · GENERATED by \`npm run seeds:ds-4\` (src/scripts/buildStudioSeeds.ts): do not edit.`,
    ` * A Lucide subset (lucide-static ${version}, ISC licence, data/studio/LICENSES.md),`,
    " * inner SVG of 24 × 24 icons drawn with stroke=currentColor. The renderer uses",
    " * them for icon elements named `lucide:<name>`.",
    " */",
    "export const LUCIDE_ICONS: Record<string, string> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const files: Record<string, string> = Object.fromEntries(Object.entries(seedFiles()).map(([rel, text]) => [path.join(DATA, rel), text]));
  files[ICONS_TS] = lucideModule();
  const stale: string[] = [];
  for (const [file, text] of Object.entries(files)) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current === text) continue;
    stale.push(path.relative(ROOT, file));
    if (!check) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
    }
  }
  // Generated files that no longer have a source.
  const walk = (dir: string): string[] => (fs.existsSync(dir) ? fs.readdirSync(dir).flatMap((n) => (fs.statSync(path.join(dir, n)).isDirectory() ? walk(path.join(dir, n)) : [path.join(dir, n)])) : []);
  const orphans = [...walk(path.join(DATA, "templates")), ...walk(path.join(DATA, "elements"))].filter((f) => !(f in files));
  for (const f of orphans) {
    stale.push(`${path.relative(ROOT, f)} (no longer generated)`);
    if (!check) fs.rmSync(f);
  }
  if (check) {
    if (stale.length) {
      console.error(`Studio seeds are stale; run \`npm run seeds:ds-4\`:\n  ${stale.join("\n  ")}`);
      process.exit(1);
    }
    console.log(`Studio seeds match the generator (${Object.keys(files).length} files).`);
  } else {
    console.log(stale.length ? `Wrote ${stale.length} file(s):\n  ${stale.join("\n  ")}` : "Studio seeds already up to date.");
  }
}

if (require.main === module) main();
